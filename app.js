const $ = id => document.getElementById(id);
const MODEL = "claude-haiku-5-5"; // cheap and fast
let pool = {}, category = "Developer", recent = [], current = null;

async function init() {
  pool = await (await fetch("tasks.json")).json();
  const saved = await chrome.storage.local.get(["category", "recent", "key"]);
  if (saved.category) category = saved.category;
  recent = saved.recent || [];
  $("key").value = saved.key || "";
  renderChips();
}

function renderChips() {
  $("chips").innerHTML = "";
  Object.keys(pool).forEach(cat => {
    const b = document.createElement("button");
    b.className = "chip"; b.textContent = cat; b.setAttribute("role", "radio");
    b.setAttribute("aria-checked", String(cat === category && !$("custom").value));
    b.onclick = () => { category = cat; $("custom").value = ""; chrome.storage.local.set({ category }); renderChips(); };
    $("chips").appendChild(b);
  });
}
$("custom").addEventListener("input", renderChips);

async function aiTask(field, effort, key) {
  const avoid = recent.slice(-8).join("; ") || "none";
  const prompt = `Give me ONE practical, hands-on task or mini project for someone interested in: ${field}.
Effort: ${effort === "Any" ? "any size" : effort}. It must be something they can actually do with common tools or materials, and clearly different from these recent ones: ${avoid}.
Reply with JSON only: {"title": "max 8 words", "description": "1-2 sentences", "steps": ["3 to 5 short steps"], "time": "estimated time"}`;
  const res = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "x-api-key": key,
      "anthropic-version": "2023-06-01",
      "anthropic-dangerous-direct-browser-access": "true"
    },
    body: JSON.stringify({ model: MODEL, max_tokens: 600, temperature: 1, messages: [{ role: "user", content: prompt }] })
  });
  if (!res.ok) throw new Error("API " + res.status);
  const data = await res.json();
  const text = data.content.map(c => c.text || "").join("").replace(/```json|```/g, "").trim();
  return JSON.parse(text);
}

function localTask(field) {
  const list = pool[field];
  if (!list) return null;
  const fresh = list.filter(t => !recent.includes(t.title));
  const src = fresh.length ? fresh : list;
  return src[Math.floor(Math.random() * src.length)];
}

function show(t, source) {
  current = t;
  $("title").textContent = t.title;
  $("desc").textContent = t.description;
  $("steps").innerHTML = "";
  (t.steps || []).forEach(s => { const li = document.createElement("li"); li.textContent = s; $("steps").appendChild(li); });
  $("source").textContent = `${source}${t.time ? " · " + t.time : ""}`;
  $("save").hidden = false;
  $("stage").classList.remove("fresh"); void $("stage").offsetWidth; $("stage").classList.add("fresh");
  recent.push(t.title); recent = recent.slice(-30);
  chrome.storage.local.set({ recent });
}

$("go").onclick = async () => {
  const field = $("custom").value.trim() || category;
  const effort = $("effort").value;
  const { key } = await chrome.storage.local.get("key");
  $("go").disabled = true; $("msg").textContent = "";
  try {
    if (key) { show(await aiTask(field, effort, key), "Generated by AI"); }
    else {
      const t = localTask(field);
      if (!t) { $("msg").textContent = "Custom fields need an API key. Open AI settings to add one."; return; }
      show(t, "From the built-in list");
    }
  } catch (e) {
    const t = localTask(field);
    if (t) show(t, "Built-in list (AI unavailable)");
    $("msg").textContent = "AI request failed. Check your key and connection.";
  } finally { $("go").disabled = false; }
};

$("save").onclick = async () => {
  const { saved = [] } = await chrome.storage.local.get("saved");
  saved.push({ ...current, field: $("custom").value.trim() || category });
  await chrome.storage.local.set({ saved });
  $("msg").textContent = "Saved.";
};

$("settings").onclick = () => $("dlg").showModal();
$("dlg").addEventListener("close", () => {
  if ($("dlg").returnValue === "save") chrome.storage.local.set({ key: $("key").value.trim() });
});
init();
